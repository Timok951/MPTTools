def set_cell_border(cell) -> None:
    tc = cell._tc
    tc_pr = tc.get_or_add_tcPr()
    tc_borders = tc_pr.first_child_found_in("w:tcBorders")
    if tc_borders is None:
        tc_borders = OxmlElement("w:tcBorders")
        tc_pr.append(tc_borders)
    for edge in ("top", "left", "bottom", "right"):
        tag = f"w:{edge}"
        element = tc_borders.find(qn(tag))
        if element is None:
            element = OxmlElement(tag)
            tc_borders.append(element)
        element.set(qn("w:val"), "single")
        element.set(qn("w:sz"), "8")
        element.set(qn("w:space"), "0")
        element.set(qn("w:color"), "000000")


def add_structured_table(doc, title_text: str, rows: list[tuple[str, str, str, str]], style) -> None:
    title = doc.add_paragraph(title_text)
    title.runs[0].bold = True
    title.paragraph_format.space_before = Pt(8)
    title.paragraph_format.space_after = Pt(4)

    table = doc.add_table(rows=1, cols=4)
    if style is not None:
        table.style = style
    table.autofit = False
    table.columns[0].width = Cm(5.2)
    table.columns[1].width = Cm(4.1)
    table.columns[2].width = Cm(2.4)
    table.columns[3].width = Cm(9.3)

    headers = ["Поле", "Ограничение", "Тип", "Описание"]
    for idx, header in enumerate(headers):
        p = table.rows[0].cells[idx].paragraphs[0]
        run = p.add_run(header)
        run.bold = True
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER

    for row in rows:
        cells = table.add_row().cells
        # Section row: first column has text, remaining columns are empty.
        if row[0] and not row[1] and not row[2] and not row[3]:
            merged = cells[0]
            for idx in (1, 2, 3):
                merged = merged.merge(cells[idx])
            p = merged.paragraphs[0]
            run = p.add_run(row[0])
            run.bold = True
            p.alignment = WD_ALIGN_PARAGRAPH.LEFT
            continue
        for i, text in enumerate(row):
            p = cells[i].paragraphs[0]
            p.add_run(text)

    for tr in table.rows:
        for tc in tr.cells:
            set_cell_border(tc)
            for paragraph in tc.paragraphs:
                paragraph.paragraph_format.space_before = Pt(0)
                paragraph.paragraph_format.space_after = Pt(0)
                paragraph.paragraph_format.line_spacing = 1
                for run in paragraph.runs:
                    run.font.size = Pt(10)


